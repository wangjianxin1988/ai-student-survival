/**
 * 按 slug 查找工具
 */
export function getToolBySlug(slug: string): Tool | undefined {
  return staticTools.find(t => t.slug === slug);
}

/**
 * 按分类找工具
 */
export function getToolsByCategory(category: string): Tool[] {
  return staticTools.filter(t => t.category === category);
}

/**
 * 找相关工具（同 category，去掉自己）
 */
export function getRelatedTools(tool: Tool, limit: number = 4): Tool[] {
  return staticTools
    .filter(t => t.category === tool.category && t.slug !== tool.slug)
    .slice(0, limit);
}

/**
 * 所有 tool slug（用于 sitemap）
 */
export function getAllToolSlugs(): string[] {
  return staticTools.map(t => t.slug).filter(Boolean);
}

